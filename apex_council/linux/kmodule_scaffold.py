"""Linux Loadable Kernel Module (.ko) Scaffold & Makefile Generator.
Zero external dependencies (pip = 0). Standard library only.
"""

from __future__ import annotations


class LinuxKernelModuleScaffold:
    """Generates standard upstream-compliant Linux Kernel Module (.ko) boilerplate."""

    @staticmethod
    def generate_c_source(module_name: str = "apex_char_dev", author: str = "Apex Sovereign", description: str = "Apex Autonomous Kernel Driver") -> str:
        safe_name = module_name.replace("-", "_").lower()
        return f"""// SPDX-License-Identifier: GPL-2.0
/*
 * {safe_name}.c - {description}
 * Autonomously synthesized by Apex Sovereign Linux Kernel Engine.
 */

#include <linux/init.h>
#include <linux/module.h>
#include <linux/kernel.h>
#include <linux/fs.h>
#include <linux/uaccess.h>
#include <linux/slab.h>

MODULE_LICENSE("GPL");
MODULE_AUTHOR("{author}");
MODULE_DESCRIPTION("{description}");
MODULE_VERSION("1.0.0");

static int debug_level = 1;
module_param(debug_level, int, 0644);
MODULE_PARM_DESC(debug_level, "Apex Kernel Debug verbosity (0=quiet, 1=verbose)");

static int __init {safe_name}_init(void)
{{
\tpr_info("Apex Kernel: [{safe_name}] Initializing driver module (debug=%d)\\n", debug_level);
\treturn 0;
}}

static void __exit {safe_name}_exit(void)
{{
\tpr_info("Apex Kernel: [{safe_name}] Cleaning up driver module\\n");
}}

module_init({safe_name}_init);
module_exit({safe_name}_exit);
"""

    @staticmethod
    def generate_makefile(module_name: str = "apex_char_dev") -> str:
        safe_name = module_name.replace("-", "_").lower()
        return f"""# Kbuild Makefile for {safe_name}
# Autonomously generated by Apex Sovereign

obj-m += {safe_name}.o

KDIR ?= /lib/modules/$(shell uname -r)/build

all:
\t$(MAKE) -C $(KDIR) M=$(PWD) modules

clean:
\t$(MAKE) -C $(KDIR) M=$(PWD) clean
"""
